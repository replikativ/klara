(ns showcases.regex
  "A regular expression matcher compiled for its pattern by a user rule.

  `matches?` is Rob Pike's backtracking matcher (literals, `.`, `*`, `^`,
  `$`), an interpreter of the pattern. The default specializer already
  compiles it for a pattern the profile shows is always the same: the
  pattern's dispatch folds away, and each `*` stays a call of the generic
  `star`. A library that knows its interpreter can do better with a rule:
  `pike` is the matcher staged by hand (the pattern known, the text code,
  the position a known number until a star has consumed an unknown number
  of characters), and a star becomes a loop.

  A rule is Klara code like any specializer, and what it produces is checked
  like any candidate: the kernel relates the loop to the recursive `star` by
  fixpoint induction (L4.check.fix). A sloppy variant of the rule, which
  skips the interpreter's (inc i) where the rest of the pattern is empty,
  is rejected: for a position that is not a number the interpreter fails
  and the sloppy matcher does not. The investor measures the default and
  the rule (attached to `matches?`) and keeps what pays."
  (:require [klara.stage :refer [code esc lift]]
            [klara.jit :as jit]
            [klara.jit.staged :as staged]
            [klara.code :as code]
            [klara.compiler :as compiler]
            [klara.investor :as investor]))

;; ---------------------------------------------------------------------------
;; The interpreter (Kernighan, "A regular expression matcher", Beautiful Code)

(declare star)

(defn here [re s i]
  (cond (empty? re) true
        (= \* (second re)) (star (first re) (rest (rest re)) s i)
        (and (= \$ (first re)) (empty? (rest re))) (= i (count s))
        (< i (count s)) (and (or (= \. (first re)) (= (first re) (nth s i)))
                             (here (rest re) s (inc i)))
        :else false))

(defn star [c re s i]
  (cond (here re s i) true
        (and (< i (count s)) (or (= c \.) (= c (nth s i)))) (star c re s (inc i))
        :else false))

;; ---------------------------------------------------------------------------
;; The rule: the matcher staged on its pattern

(defn- dyn [i] (if (number? i) (lift i) i))

(defn- advance
  "The rest of the match at position i+1, generated by k: a known position
   is advanced now; code is advanced once, where the interpreter advances it
   (it computes (inc i) before it looks at the rest of the pattern)."
  [i k]
  (if (number? i) (k (inc i)) (code (let [j (inc (esc i))] (esc (k (code j)))))))

(defn- skip
  "The sloppy advance: no (inc i) unless the rest of the pattern needs it."
  [i k]
  (if (number? i) (k (inc i)) (k (code (inc (esc i))))))

(defn- test-char [c s i then]
  (if (= c \.)
    then
    (code (if (= (esc (lift c)) (nth (esc s) (esc (dyn i)))) (esc then) false))))

(declare gen-star)

(defn gen-here [adv re s i]
  (cond (empty? re) (code true)
        (= \* (second re)) (gen-star adv (first re) (rest (rest re)) s i)
        (and (= \$ (first re)) (empty? (rest re))) (code (= (esc (dyn i)) (count (esc s))))
        :else (code (if (< (esc (dyn i)) (count (esc s)))
                      (esc (test-char (first re) s i (adv i (fn [j] (gen-here adv (rest re) s j)))))
                      false))))

(defn gen-star [adv c re s i]
  (code (loop [j (esc (dyn i))]
          (if (esc (gen-here adv re s (code j)))
            true
            (if (< j (count (esc s)))
              (esc (test-char c s (code j) (code (recur (inc j)))))
              false)))))

(defn- matcher-rule
  "A rule (L4.jit.rules): a call of `here` on a known pattern is the staged
   matcher for it."
  [nm adv]
  {:name nm
   :fn (fn [m]
         (when (and (= :app (:point m))
                    (= 'showcases.regex/here (:name (code/view (staged/->code (:fn m)))))
                    (staged/static? (first (:args m))))
           (let [[re s i] (:args m)]
             (staged/dynamic (gen-here adv (staged/value re) (staged/->code s)
                                       (if (staged/static? i) (staged/value i) (staged/->code i)))))))})

(def pike (matcher-rule :pike advance))
(def sloppy (matcher-rule :sloppy skip))

(defn with-pike [ctx default] (jit/default ctx {:rules [pike]}))

;; ---------------------------------------------------------------------------
;; The program

(defn ^{:klara/specialize with-pike} matches? [pattern s]
  (let [re (seq pattern)]
    (if (= \^ (first re))
      (here (rest re) s 0)
      (loop [i 0]
        (cond (here re s i) true
              (< i (count s)) (recur (inc i))
              :else false)))))

(defn count-matches [pattern texts]
  (loop [i 0 n 0]
    (if (< i (count texts))
      (recur (inc i) (if (matches? pattern (nth texts i)) (inc n) n))
      n)))

(def logs (vec (for [i (range 200)]
                 (str (apply str (repeat (mod i 17) \x)) "abb" (apply str (repeat (mod i 5) \b))
                      (if (even? i) "c" "d")))))

(defn ns-per-match [runs]
  (let [t (System/nanoTime)
        n (loop [i 0 n 0] (if (< i runs) (recur (inc i) (count-matches "ab*c" logs)) n))]
    [(quot (- (System/nanoTime) t) (* runs (count logs))) n]))

;; A morning of log filtering, always the same pattern. The driver loop is
;; compiled in both measurements: what changes is the matcher.
(dotimes [_ 20] (count-matches "ab*c" logs))
(compiler/optimize! 'showcases.regex/count-matches)
(dotimes [_ 5] (count-matches "ab*c" logs))
(def before (ns-per-match 5))

;; The sloppy rule is checked like any candidate, and fails.
(def sloppy-outcome (jit/prepare 'showcases.regex/matches? {:specializer (fn [ctx d] (jit/default ctx {:rules [sloppy]}))}))

(def decisions (investor/invest! 'showcases.regex {:explore-ns 0}))
(dotimes [_ 200] (count-matches "ab*c" logs))
(def after (ns-per-match 2000))

(def checks
  (let [texts (into logs ["" "ac" "abc" "abbbbbbbbc" "xxabd" "c"])]
    (= (mapv #(matches? "ab*c" %) texts)
       (mapv #(staged/interpret (compiler/reference 'showcases.regex/matches?) "ab*c" %) texts))))

(defn row [d]
  (str (name (:name d)) ": " (name (:decision d))
       (when (:chosen d) (str " with " (name (:chosen d))))
       (when (:interpreted-ns d)
         (apply str ", interpreted " (:interpreted-ns d) " ns"
                (for [a (:alternatives d)]
                  (str ", " (name (:name a)) " " (or (:ns-per-call a) (name (:status a)))
                       (when (:ns-per-call a) " ns")))))))

(doseq [d decisions] (println (row d)))
(println "the sloppy rule:" (name (:status sloppy-outcome)))
(println "per match:" (first before) "ns interpreted," (first after) "ns compiled")

{:decisions (into {} (map (juxt :name :decision) decisions))
 :chosen (into {} (keep #(when (:chosen %) [(:name %) (:chosen %)]) decisions))
 :rules (:rules (:provenance (compiler/explain matches?)))
 :sloppy (:status sloppy-outcome)
 :same-result (= (second before) (second after))
 :agree checks
 :speedup (/ (first before) (max 1 (first after)))}
